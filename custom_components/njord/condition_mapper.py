"""Map WMO weather codes to Home Assistant condition strings."""

from __future__ import annotations

from homeassistant.components.weather import (
    ATTR_CONDITION_CLEAR_NIGHT,
    ATTR_CONDITION_CLOUDY,
    ATTR_CONDITION_FOG,
    ATTR_CONDITION_HAIL,
    ATTR_CONDITION_LIGHTNING_RAINY,
    ATTR_CONDITION_PARTLYCLOUDY,
    ATTR_CONDITION_POURING,
    ATTR_CONDITION_RAINY,
    ATTR_CONDITION_SNOWY,
    ATTR_CONDITION_SUNNY,
)

# (day_condition, night_condition)
WMO_TO_HA: dict[int, tuple[str, str]] = {
    0: (ATTR_CONDITION_SUNNY, ATTR_CONDITION_CLEAR_NIGHT),
    1: (ATTR_CONDITION_PARTLYCLOUDY, ATTR_CONDITION_PARTLYCLOUDY),
    2: (ATTR_CONDITION_PARTLYCLOUDY, ATTR_CONDITION_PARTLYCLOUDY),
    3: (ATTR_CONDITION_CLOUDY, ATTR_CONDITION_CLOUDY),
    45: (ATTR_CONDITION_FOG, ATTR_CONDITION_FOG),
    48: (ATTR_CONDITION_FOG, ATTR_CONDITION_FOG),
    51: (ATTR_CONDITION_RAINY, ATTR_CONDITION_RAINY),
    53: (ATTR_CONDITION_RAINY, ATTR_CONDITION_RAINY),
    55: (ATTR_CONDITION_RAINY, ATTR_CONDITION_RAINY),
    56: (ATTR_CONDITION_RAINY, ATTR_CONDITION_RAINY),
    57: (ATTR_CONDITION_RAINY, ATTR_CONDITION_RAINY),
    61: (ATTR_CONDITION_RAINY, ATTR_CONDITION_RAINY),
    63: (ATTR_CONDITION_RAINY, ATTR_CONDITION_RAINY),
    65: (ATTR_CONDITION_POURING, ATTR_CONDITION_POURING),
    66: (ATTR_CONDITION_RAINY, ATTR_CONDITION_RAINY),
    67: (ATTR_CONDITION_POURING, ATTR_CONDITION_POURING),
    71: (ATTR_CONDITION_SNOWY, ATTR_CONDITION_SNOWY),
    73: (ATTR_CONDITION_SNOWY, ATTR_CONDITION_SNOWY),
    75: (ATTR_CONDITION_SNOWY, ATTR_CONDITION_SNOWY),
    77: (ATTR_CONDITION_SNOWY, ATTR_CONDITION_SNOWY),
    80: (ATTR_CONDITION_RAINY, ATTR_CONDITION_RAINY),
    81: (ATTR_CONDITION_RAINY, ATTR_CONDITION_RAINY),
    82: (ATTR_CONDITION_POURING, ATTR_CONDITION_POURING),
    85: (ATTR_CONDITION_SNOWY, ATTR_CONDITION_SNOWY),
    86: (ATTR_CONDITION_SNOWY, ATTR_CONDITION_SNOWY),
    95: (ATTR_CONDITION_LIGHTNING_RAINY, ATTR_CONDITION_LIGHTNING_RAINY),
    96: (ATTR_CONDITION_HAIL, ATTR_CONDITION_HAIL),
    99: (ATTR_CONDITION_HAIL, ATTR_CONDITION_HAIL),
}


_KNOWN_CODES = sorted(WMO_TO_HA.keys())


def _nearest_wmo_code(code: int) -> int:
    """Find the nearest known WMO code."""
    return min(_KNOWN_CODES, key=lambda c: abs(c - code))


def map_condition(weather_code: int, is_day: bool) -> str:
    """Map a WMO weather code + is_day flag to an HA condition string."""
    pair = WMO_TO_HA.get(weather_code)
    if pair is None:
        pair = WMO_TO_HA[_nearest_wmo_code(weather_code)]
    return pair[0] if is_day else pair[1]
